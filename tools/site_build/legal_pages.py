def main_html(items, date):
    chunks = [c.strip() for c in re.split(r"(?=<h2>)", html_blocks(items)) if c.strip()]
    secs = "".join(f'<section class="card art-sec">{c}</section>' for c in chunks)
    return f'''<main class="wrap stack art-main article legal">
        <p class="legal-date">עודכן לאחרונה: {date}</p>
{secs}
    </main>'''


def build():
    for name, title, desc, h1, lead, visual, items, date in PAGES:
        html = home2.inner_page(title, desc, "", h1, lead, visual, main_html(items, date),
                                legacy_v=CSS_VERSION, buttons=False)
        open(os.path.join(SITE, name), "w").write(html)
        print(f"{name} done")


if __name__ == "__main__":
    build()
