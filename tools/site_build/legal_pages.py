def html_blocks(items):
    """[(כותרת, [פסקה | [פריטי רשימה]])] -> HTML עם <h2> לכל מקטע."""
    out = []
    for h, paras in items:
        out.append(f"<h2>{h}</h2>")
        for p in paras:
            if isinstance(p, list):
                out.append("<ul>" + "".join(f"<li>{x}</li>" for x in p) + "</ul>")
            else:
                out.append(f"<p>{p}</p>")
    return "\n".join(out)


